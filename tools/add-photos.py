#!/usr/bin/env python3
"""Import favorite film photos from a zip into film_photos/.

Run from the repo root:

    python3 tools/add-photos.py              # uses DEFAULT_ZIP below
    python3 tools/add-photos.py --dry-run    # show what would happen, write nothing
    python3 tools/add-photos.py --zip ~/Downloads/2027_Favorite_Film.zip

For every new image in the zip this writes a resized full-size JPEG to
film_photos/full/ and a thumbnail to film_photos/thumbs/, and records the
entry in film_photos/manifest.json so it is never processed twice.

Entries listed under "skip" in film_photos/import-options.json are left out
(e.g. a raw scan that already has an edited copy in the zip).

It never modifies the zip, never edits HTML, and writes only under
film_photos/. Resizing needs ImageMagick (`magick`, or `convert` on older
installs).
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

# The zip of favorites to import. Override with --zip for other years.
DEFAULT_ZIP = Path.home() / "Downloads" / "2026_Favorite_Film.zip"

REPO_ROOT = Path(__file__).resolve().parent.parent
PHOTOS_DIR = REPO_ROOT / "film_photos"
FULL_DIR = PHOTOS_DIR / "full"
THUMBS_DIR = PHOTOS_DIR / "thumbs"
MANIFEST_PATH = PHOTOS_DIR / "manifest.json"
OPTIONS_PATH = PHOTOS_DIR / "import-options.json"

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".tif", ".tiff", ".heic", ".heif"}

FULL_LONG_EDGE = 1800
FULL_QUALITY = 82
THUMB_WIDTH = 440
THUMB_QUALITY = 80

MANIFEST_NOTE = (
    "Generated by tools/add-photos.py. Do not edit by hand. Maps each zip "
    "entry to its output name in film_photos/full and film_photos/thumbs, "
    "with the entry's CRC-32 and size so unchanged photos are skipped."
)


def find_imagemagick():
    """Return the ImageMagick command to use, or None if it isn't installed."""
    if shutil.which("magick"):
        return ["magick"]
    if shutil.which("convert"):
        return ["convert"]
    return None


def imagemagick_help():
    return (
        "ImageMagick is required to resize photos but was not found.\n"
        "Install it, then run this script again:\n"
        "  Ubuntu/Debian:  sudo apt install imagemagick\n"
        "  macOS:          brew install imagemagick\n"
        "  Windows:        https://imagemagick.org/script/download.php\n"
        "For HEIC photos, ImageMagick also needs libheif "
        "(Ubuntu/Debian: sudo apt install libheif1)."
    )


def output_name(entry_name):
    """'Some Folder/IMG 0042.JPG' -> 'img-0042'."""
    stem = Path(entry_name).stem.lower()
    stem = re.sub(r"[^a-z0-9]+", "-", stem).strip("-")
    return stem or "photo"


def is_importable(info):
    """True for image files, False for folders, macOS junk and hidden files."""
    if info.is_dir():
        return False
    parts = info.filename.split("/")
    if "__MACOSX" in parts or any(part.startswith(".") for part in parts):
        return False
    return Path(info.filename).suffix.lower() in IMAGE_EXTENSIONS


def load_manifest():
    if not MANIFEST_PATH.exists():
        return {"_note": MANIFEST_NOTE, "zips": {}}
    with open(MANIFEST_PATH, encoding="utf-8") as f:
        manifest = json.load(f)
    manifest.setdefault("zips", {})
    return manifest


def load_skip_list(zip_key):
    """Zip entries never to import, from the hand-edited import-options.json."""
    if not OPTIONS_PATH.exists():
        return set()
    with open(OPTIONS_PATH, encoding="utf-8") as f:
        return set(json.load(f).get(zip_key, {}).get("skip", []))


def save_manifest(manifest):
    """Write the manifest atomically so an interrupted run can't corrupt it."""
    manifest["_note"] = MANIFEST_NOTE
    tmp_path = MANIFEST_PATH.with_suffix(".json.tmp")
    with open(tmp_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
        f.write("\n")
    os.replace(tmp_path, MANIFEST_PATH)


def outputs_exist(name):
    return (FULL_DIR / f"{name}.jpg").exists() and (THUMBS_DIR / f"{name}.jpg").exists()


def unique_name(base, taken):
    """Append -2, -3, ... until the name isn't used by another entry or file."""
    name, n = base, 2
    while name in taken:
        name = f"{base}-{n}"
        n += 1
    return name


def resize(magick, src, dest, geometry, quality):
    """Resize src into dest as a stripped, auto-oriented JPEG."""
    subprocess.run(
        magick + [
            f"{src}[0]",                 # first frame/page only (TIFF, HEIC)
            "-auto-orient",
            "-background", "white", "-alpha", "remove", "-alpha", "off",
            "-resize", geometry,
            "-strip",
            "-interlace", "Plane",
            "-quality", str(quality),
            f"JPEG:{dest}",
        ],
        check=True,
        capture_output=True,
        text=True,
    )


def process(magick, zf, info, name, workdir):
    """Extract one entry to workdir, write its full and thumb JPEGs."""
    src = workdir / ("source" + Path(info.filename).suffix.lower())
    with zf.open(info) as entry, open(src, "wb") as out:
        shutil.copyfileobj(entry, out)
    try:
        full_tmp = workdir / "full.jpg"
        thumb_tmp = workdir / "thumb.jpg"
        resize(magick, src, full_tmp, f"{FULL_LONG_EDGE}x{FULL_LONG_EDGE}>", FULL_QUALITY)
        resize(magick, src, thumb_tmp, f"{THUMB_WIDTH}x>", THUMB_QUALITY)
        FULL_DIR.mkdir(parents=True, exist_ok=True)
        THUMBS_DIR.mkdir(parents=True, exist_ok=True)
        shutil.move(full_tmp, FULL_DIR / f"{name}.jpg")
        shutil.move(thumb_tmp, THUMBS_DIR / f"{name}.jpg")
    finally:
        src.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--zip", type=Path, default=DEFAULT_ZIP,
                        help=f"zip of photos to import (default: {DEFAULT_ZIP})")
    parser.add_argument("--dry-run", action="store_true",
                        help="show what would be processed without writing anything")
    args = parser.parse_args()

    zip_path = args.zip.expanduser()
    if not zip_path.is_file():
        print(f"Zip not found: {zip_path}\nNothing was changed.")
        return 1

    magick = find_imagemagick()
    if magick is None and not args.dry_run:
        print(imagemagick_help())
        return 1

    manifest = load_manifest()
    zip_key = zip_path.name
    known = manifest["zips"].setdefault(zip_key, {})
    skip = load_skip_list(zip_key)

    # Names already claimed by any entry (from any zip) or by a file on disk.
    taken = {rec["name"] for recs in manifest["zips"].values() for rec in recs.values()}
    if FULL_DIR.is_dir():
        taken |= {p.stem for p in FULL_DIR.glob("*.jpg")}

    new, changed, regenerated, failed = [], [], [], []
    skipped = 0

    with zipfile.ZipFile(zip_path) as zf:
        entries = sorted((i for i in zf.infolist() if is_importable(i)),
                         key=lambda i: i.filename)
        in_zip = {i.filename for i in entries}
        excluded = sorted(i.filename for i in entries if i.filename in skip)
        entries = [i for i in entries if i.filename not in skip]

        with tempfile.TemporaryDirectory(prefix="add-photos-") as tmp:
            workdir = Path(tmp)
            for info in entries:
                rec = known.get(info.filename)
                if rec and rec["crc32"] == info.CRC and rec["size"] == info.file_size:
                    if outputs_exist(rec["name"]):
                        skipped += 1
                        continue
                    bucket, name = regenerated, rec["name"]
                elif rec:
                    bucket, name = changed, rec["name"]
                else:
                    bucket, name = new, unique_name(output_name(info.filename), taken)
                    taken.add(name)

                if args.dry_run:
                    bucket.append((info.filename, name))
                    continue

                try:
                    process(magick, zf, info, name, workdir)
                except subprocess.CalledProcessError as err:
                    failed.append((info.filename, (err.stderr or "").strip()))
                    continue

                known[info.filename] = {"name": name, "crc32": info.CRC,
                                        "size": info.file_size}
                save_manifest(manifest)  # after each photo, so progress survives a crash
                bucket.append((info.filename, name))

    missing = sorted(set(known) - in_zip)
    unmatched = sorted(skip - in_zip)

    prefix = "[dry run] would process: " if args.dry_run else ""
    summary = (f"{prefix}{len(new)} new, {skipped} skipped, {len(changed)} changed, "
               f"{len(missing)} missing from zip")
    if excluded:
        summary += f", {len(excluded)} excluded by import-options.json"
    if regenerated:
        summary += f", {len(regenerated)} regenerated (output files were missing)"
    if failed:
        summary += f", {len(failed)} failed"
    print(summary)

    for entry, name in changed:
        print(f"  changed in zip, reprocessed: {entry} -> {name}.jpg")
    for entry, name in regenerated:
        print(f"  regenerated missing files: {entry} -> {name}.jpg")
    for entry in missing:
        print(f"  no longer in zip (left in place; delete by hand if unwanted): "
              f"{entry} -> {known[entry]['name']}.jpg")
    for entry in excluded:
        if entry in known:
            print(f"  excluded but imported earlier (files left in place): {entry}")
    for entry in unmatched:
        print(f"  import-options.json skips an entry that isn't in the zip: {entry}")
    for entry, message in failed:
        print(f"  FAILED: {entry}: {message or 'ImageMagick error'}")

    if new:
        print("\nNew photos:")
        for entry, name in new:
            renamed = "" if name == output_name(entry) else f"   (renamed from {entry} to avoid a clash)"
            print(f"  {name}.jpg{renamed}")
        if not args.dry_run:
            print("\nNext: add a <figure class=\"photo-card\"> block for each new photo "
                  "to its roll page and/or the Favorites grid on film.html, with the "
                  "photo's film stock and year-month caption (e.g. Kodak Portra 400 · 2026-10).")

    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
